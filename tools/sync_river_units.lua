package.path="game/scripts/vscripts/?.lua;"..package.path
local B=require("rift.core.config").river_camps
local check=arg[1]=="--check"
local function save(p,s)
 local f=io.open(p,"rb");local old=f and f:read("*a")or"";if f then f:close()end
 if old:gsub("\r\n","\n")==s:gsub("\r\n","\n")then return end
 assert(not check,"river units out of sync: "..p);f=assert(io.open(p,"wb"));f:write(s);f:close()
end
local lines={'// Generated by tools/sync_river_units.lua.','"DOTAUnits"','{'}
for _,d in ipairs(B.members)do
 lines[#lines+1]=' "'..d.unit..'"\n {'
 local kv={BaseClass="npc_dota_creature",Model=d.model,ModelScale=d.size,Level=1,IsNeutralUnitType=1,
 AttackCapabilities=d.ranged and"DOTA_UNIT_CAP_RANGED_ATTACK"or"DOTA_UNIT_CAP_MELEE_ATTACK",
 AttackDamageMin=d.damage,AttackDamageMax=d.damage,AttackRate=1.7,AttackAnimationPoint=.3,
 AttackRange=d.ranged and 350 or 120,AttackAcquisitionRange=B.aggro,
 ProjectileModel=d.ranged and"particles/base_attacks/ranged_badguy.vpcf"or"",ProjectileSpeed=900,
 MovementCapabilities="DOTA_UNIT_CAP_MOVE_GROUND",MovementSpeed=280,StatusHealth=d.health,StatusMana=0,
 ArmorPhysical=d.armor,MagicalResistance=25,VisionDaytimeRange=B.aggro,VisionNighttimeRange=B.aggro,
 BoundsHullName="DOTA_HULL_SIZE_REGULAR",BountyGoldMin=0,BountyGoldMax=0,BountyXP=0}
 local keys={};for k in pairs(kv)do keys[#keys+1]=k end;table.sort(keys)
 for _,k in ipairs(keys)do lines[#lines+1]='  "'..k..'" "'..kv[k]..'"'end
 lines[#lines+1]=' }'
end
lines[#lines+1]='}\n';save("game/scripts/npc/npc_river_units.txt",table.concat(lines,"\n"))
local path="game/scripts/npc/npc_units_custom.txt";local f=assert(io.open(path,"rb"));local s=f:read("*a");f:close()
if not s:find('#base "npc_river_units.txt"',1,true)then s='#base "npc_river_units.txt"\n'..s end;save(path,s)
for _,lang in ipairs({"russian","english"})do
 local p="game/resource/addon_"..lang..".txt";local f=assert(io.open(p,"rb"));local txt=f:read("*a");f:close()
 local names=lang=="russian" and {"Речной копейщик","Речной заклинатель","Речной страж"}or{"River Spearfrog","River Tidecaller","River Guardian"}
 for i,d in ipairs(B.members)do
  local key=d.unit;local line='"'..key..'" "'..names[i]..'"';local pat='"'..key..'"%s*"[^"\n]*"'
  if txt:find(pat)then txt=txt:gsub(pat,function()return line end)
  else txt=txt:gsub('%s*}%s*}%s*$',function()return '\n\t\t'..line..'\n\t}\n}\n'end)end
 end
 save(p,txt)
end
print("River unit KV / localization synchronized")
