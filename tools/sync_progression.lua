-- Generate native talent KV, path descriptions and the balance reference from
-- hero_balance. --check is read-only. No progression values live in Panorama.
package.path="game/scripts/vscripts/?.lua;"..package.path
local B=require("rift.data.hero_balance").progression
local function read(p)local f=assert(io.open(p,"rb"));local s=f:read("*a");f:close();return s end
local checking=arg and arg[1]=="--check"
local function save(p,s)
 local f=io.open(p,"rb");local old=f and f:read("*a")or"";if f then f:close()end
 if old:gsub("\r\n","\n")==s:gsub("\r\n","\n")then return end
 assert(not checking,"progression generated file out of sync: "..p)
 f=assert(io.open(p,"wb"));f:write(s);f:close()
end
local labels={
 attack_damage={"урона атаки","attack damage"},health={"здоровья","health"},
 attack_speed={"скорости атаки","attack speed"},move_speed={"скорости передвижения","movement speed"},
 spell_amp={"% усиления заклинаний","% spell amplification"},mana_regen={"маны/сек","mana/sec"},
 cast_range={"дальности заклинаний","cast range"},ult_cast_range={"дальности навыка пути","branch ability cast range"},
 ult_radius={"радиуса / полуширины","branch ability radius/half-width"},
 ult_cooldown_pct={"% сокращения кд навыка пути","% branch ability cooldown reduction"},
 ult_damage_pct={"% урона навыка пути","% branch ability damage"},
 ult_ticks={"импульсов / залпов","branch ability pulses/volleys"},
 ult_duration={"сек. длительности стойки","seconds stance duration"},pull_distance={"дальности притягивания R","R pull distance"},
 jug_attack_cdr={"сек. сокращения кд R обычной атакой","seconds R cooldown reduction per ordinary attack"},
 champion_health_pct={"% здоровья воина Duel","% Duel warrior health"},champion_damage_pct={"% урона воина Duel","% Duel warrior damage"},
 courage_lifesteal={"п.п. вампиризма контратаки","percentage points counterattack lifesteal"},
 courage_attacks={"атака до контратаки","attacks to counterattack"},
 statue_arrow_bonus={"урона лучей статуи","statue beam damage"},statue_cooldown_reduction={"сек. сокращения кд статуи","seconds statue cooldown reduction"},
 statue_beam_range={"дальности лучей статуи","statue beam range"},sphere_damage_pct={"% урона сферы","% sphere damage"},
 sf_duration={"сек. длительности сфер/крыльев","seconds sphere/wing duration"},sphere_regen_reduction={"сек. восстановления сферы","seconds sphere regeneration time"},
 ring_damage_bonus={"урона каждого кольца","damage per ring"},ring_radius={"радиуса колец койлов","circular raze ring radius"},
 spirit_crit_bonus={"п.п. множителя критического удара духа","percentage points spirit critical multiplier"},
 spirit_cooldown_reduction={"сек. сокращения кд духа","seconds spirit cooldown reduction"},
 chain_damage_bonus={"урона цепной молнии","chain lightning damage"},chain_chance_bonus_pct={"п.п. шанса молнии","percentage points lightning chance"},
 crystal_durability={"атак до разрушения кристалла","crystal durability attacks"},crystal_lifetime={"сек. жизни кристалла","seconds crystal lifetime"},
 crystal_cooldown_reduction={"сек. сокращения кд кристалла","seconds crystal cooldown reduction"},
 blast_damage_bonus={"урона пси-взрыва","psionic blast damage"},refraction_instances={"зарядов щита Refraction","Refraction shield charges"},
}
local function keys(t)local o={};for k in pairs(t)do o[#o+1]=k end;table.sort(o);return o end
local function describe(t,lang)
 local out={};for _,k in ipairs(keys(t))do assert(labels[k],"missing effect label "..k);local sign=(k=="sphere_regen_reduction"or k=="courage_attacks")and"−"or"+";out[#out+1]=sign..string.format("%g",t[k]).." "..labels[k][lang]end
 return table.concat(out,"; ")
end
local function name(hero,path,i)return "special_bonus_duality_"..hero:gsub("npc_dota_hero_","").."_"..path.."_"..i end
local kv={'// Generated by tools/sync_progression.lua.','"DOTAAbilities"','{'}
local heroes={'// Generated native talent slots. Q/W/E/R, innates and facets are inherited.','"DOTAHeroes"','{'}
local loc={read("game/resource/addon_russian.txt"),read("game/resource/addon_english.txt")}
local function token(lang,k,v)
 local line='"'..k..'" "'..v..'"'
 local pattern='"'..k..'"%s*"[^"\n]*"'
 if loc[lang]:find(pattern)then loc[lang]=loc[lang]:gsub(pattern,function()return line end)
 else loc[lang]=loc[lang]:gsub('%s*}%s*}%s*$',function()return '\n\t\t'..line..'\n\t}\n}\n'end)end
end
local ability_path="game/scripts/npc/npc_abilities_custom.txt"
local abilities=read(ability_path)
if not abilities:find('#base "npc_progression_abilities.txt"',1,true)then abilities='#base "npc_progression_abilities.txt"\n'..abilities end
local doc={"# DUALITY — таланты и Aghanim по веткам","","Сгенерировано из `hero_balance.lua`. Числа — первый баланс для playtest. Выбор пути остаётся при первом изучении R на уровне 6. Таланты используют штатные уровни 10/15/20/25 и очки способностей.","","Scepter и Shard дают дополнительные эффекты выбранной ветки. Штатные улучшения обычных навыков Dota сохраняются. Бонусы области ограничены +20% исходного радиуса/полуширины; дополнительные импульсы суммарно ограничены двумя. Процентное сокращение кд пути ограничено 35%; плоские улучшения сборки применяются отдельно.",""}
for _,hero in ipairs(keys(B.heroes))do
 local paths=B.heroes[hero]
 heroes[#heroes+1]=' "'..hero..'"\n {'
 for i=1,8 do heroes[#heroes+1]='  "Ability'..(9+i)..'" "'..name(hero,"physical",i)..'"'end
 heroes[#heroes+1]=' }'
 doc[#doc+1]='## '..hero:gsub("npc_dota_hero_","")
 doc[#doc+1]='\n| Уровень | Физическая ветка (два выбора) | Магическая ветка (два выбора) |\n|---|---|---|'
 for tier,level in ipairs(B.levels)do local i=tier*2-1
  doc[#doc+1]='| '..level..' | '..describe(paths.physical.talents[i],1)..' **или** '..describe(paths.physical.talents[i+1],1)..' | '..describe(paths.magical.talents[i],1)..' **или** '..describe(paths.magical.talents[i+1],1)..' |'
 end
 for _,path in ipairs({"physical","magical"})do local d=paths[path]
  for i,t in ipairs(d.talents)do
   local n=name(hero,path,i)
   kv[#kv+1]=' "'..n..'"\n {\n  "BaseClass" "ability_lua"\n  "ScriptFile" "rift/abilities/branch_talent"\n  "AbilityType" "ABILITY_TYPE_ATTRIBUTES"\n  "AbilityBehavior" "DOTA_ABILITY_BEHAVIOR_PASSIVE"\n  "RequiredLevel" "'..B.levels[math.ceil(i/2)]..'"\n  "MaxLevel" "1"\n }'
   for lang=1,2 do
    token(lang,"DOTA_Tooltip_ability_"..n,describe(t,lang))
    token(lang,"DOTA_Tooltip_ability_"..n.."_Description",(lang==1 and "Один талант на ступень 10/15/20/25. Противоположные таланты открываются на 27/28/29/30 уровнях. Эффекты области и импульсов учитывают общий лимит усилений пути."or"One choice per tier at 10/15/20/25. Opposite talents unlock at 27/28/29/30. Area and pulse effects share the branch enhancement caps."))
   end
  end
  for _,item in ipairs({"scepter","shard"})do
   for lang=1,2 do token(lang,"DOTA_Tooltip_ability_"..d.ult.."_"..item.."_description",describe(d[item],lang)..(lang==1 and ". Дополнительное улучшение пути DUALITY. Штатные улучшения обычных навыков сохраняются."or". Additional DUALITY path enhancement. Native basic-ability upgrades remain available."))end
  end
  abilities=abilities:gsub('("'..d.ult..'"%s*)(%b{})',function(head,block)
   for _,flag in ipairs({"HasScepterUpgrade","HasShardUpgrade"})do
    if not block:find('"'..flag..'"',1,true)then block=block:sub(1,-2)..'\n "'..flag..'" "1"\n}'end
   end
   return head..block
  end)
  doc[#doc+1]='\n'..(path=="physical"and"Физическая"or"Магическая")..': **Scepter** — '..describe(d.scepter,1)..'; **Shard** — '..describe(d.shard,1)..'.'
 end
 doc[#doc+1]=''
end
kv[#kv+1]='}\n';heroes[#heroes+1]='}\n'
save("game/scripts/npc/npc_progression_abilities.txt",table.concat(kv,"\n"))
save("game/scripts/npc/npc_heroes_custom.txt",table.concat(heroes,"\n"))
save(ability_path,abilities)
save("game/resource/addon_russian.txt",loc[1]);save("game/resource/addon_english.txt",loc[2])
save("docs/BRANCH_PROGRESSION.md",table.concat(doc,"\n"))
print("Native branch talents and Scepter/Shard descriptions synchronized (11 heroes, 176 talents)")
