#!/usr/bin/env python3
"""Adapt a Hammer-saved Valve Forest Solo copy to DUALITY.

The installed Workshop Tools example must first be saved as vmap 40+ in
Hammer. Original Valve files are never modified. See docs/ARENA_BUILD.md.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import uuid
from vendor import datamodel as dm

ROOT = Path(__file__).resolve().parents[1]
TEAMS = [2, 3, 6, 7, 8, 9, 10, 11]
FLAT_RADIUS = 2304
FLAT_LEVEL = 0
# Original Forest-derived source outside the central island, before revision 2.
SOURCE_OUTER_TERRAIN_SHA256 = "e72497041fc007c9b3a651a393c1e9bbab1268b9bca068466147fb7a4b930f89"


def outer_terrain_digest(layer):
    """The revision may change only height/water inside the combat circle."""
    values = []
    for key in ['verticesHeight', 'verticesWater']:
        values.append([v for i, v in enumerate(layer[key])
                       if math.hypot(-8192+(i % 65)*256, -8192+(i // 65)*256) > FLAT_RADIUS])
    for key in ['edgesPath', 'objectsTreeType', 'objectsTreeSize',
                'cellsTileSet', 'cellsMaterialSet', 'gridnavFlags']:
        values.append(list(layer[key]))
    return hashlib.sha256(json.dumps(values, separators=(',', ':')).encode()).hexdigest()


def revise_arena(model, layout):
    """Flat central combat ground and eight authored sanctuary anchors.

    Tile geometry is regenerated by native Tools from the height/water arrays.
    The old central skip-solid and the stairs around the removed plateau are
    explicitly removed, rather than hidden with runtime teleport corrections.
    """
    world = model.root['world']
    layer = next(e for e in model.elements if e.type == 'CMapDotaTileGrid')['layerData'][0]
    before = outer_terrain_digest(layer)
    assert before == SOURCE_OUTER_TERRAIN_SHA256, "Restore the original outer terrain before revising the center"
    removed = []
    def keep(e):
        x, y, _ = e.get('origin', [99999, 99999, 0])
        if e.type == 'CMapMesh' and math.hypot(x, y) < 512:
            if 'materials/tools/toolsskip.vmat' in e['meshData']['materials']:
                removed.append('central_skip_solid')
                return False
        if e.type == 'CMapEntity' and math.hypot(x, y) < 1200:
            p = e['entity_properties']
            if p.get('classname') == 'prop_static' and p.get('model', '').startswith('models/props_structures/stair_'):
                removed.append('old_plateau_stair')
                return False
        if 'children' in e:
            e['children'] = dm.make_array([c for c in e['children'] if keep(c)], dm.Element)
        return True
    keep(world)
    for y in range(65):
        for x in range(65):
            if math.hypot(-8192+x*256, -8192+y*256) <= FLAT_RADIUS:
                i = y*65+x
                layer['verticesHeight'][i] = FLAT_LEVEL
                layer['verticesWater'][i] = False
    assert outer_terrain_digest(layer) == before
    nodes = []
    def walk(e):
        nodes.append(e)
        for c in e.get('children', []): walk(c)
    walk(world)
    entities = {e['entity_properties'].get('targetname', ''): e for e in nodes if e.type == 'CMapEntity'}
    node = max(e.get('nodeID', 0) for e in model.elements)+1
    def anchor(name, x, y, z, team):
        nonlocal node
        e = entities.get(name)
        if e is None:
            uid = uuid.uuid5(uuid.NAMESPACE_URL, 'duality/sanctuary/'+name)
            e = model.add_element(name, 'CMapEntity', id=uid)
            e['nodeID'], e['referenceID'] = node, dm.UInt64(0); node += 1
            e['children'] = dm.make_array([], dm.Element)
            e['angles'], e['scales'] = dm.Angle([0,0,0]), dm.Vector3([1,1,1])
            e['editorOnly'], e['force_hidden'], e['isProceduralEntity'] = False, False, False
            e['variableTargetKeys'], e['variableNames'] = dm.make_array([],str), dm.make_array([],str)
            e['hitNormal'] = dm.Vector3([0,0,1])
            p = model.add_element(name+'_properties','EditGameClassProps',id=uuid.uuid5(uid,'properties'))
            p['classname'], p['targetname'], p['teamnumber'] = 'info_target', name, str(team)
            e['entity_properties'] = p; world['children'].append(e)
        e['origin'] = dm.Vector3([x,y,z])
    for p in layout['relics']:
        p['z'] = 128 + FLAT_LEVEL*128; entities[p['name']]['origin'] = dm.Vector3([p['x'],p['y'],p['z']])
    entities['rift_center']['origin'] = dm.Vector3([0,0,128 + FLAT_LEVEL*128])
    for team, base in zip(TEAMS, layout['bases']):
        x,y = base['x'],base['y']; r = math.hypot(x,y)
        ix,iy = -x/r,-y/r
        tx,ty = round(x+ix*320-iy*220),round(y+iy*320+ix*220)
        base.update(team=team,name=f'rift_base_{team}',z=128,
                    tower={'name':f'rift_base_tower_{team}','x':tx,'y':ty,'z':128})
        anchor(base['name'],x,y,128,team)
        anchor(base['tower']['name'],tx,ty,128,team)
    layout.update(revision=2, flat_radius=FLAT_RADIUS, flat_level=FLAT_LEVEL,
                  outer_terrain_sha256=before, terrain_sha256=terrain_digest(layer))
    print('Arena revision 2:', len(removed), 'obsolete center objects removed; flat radius', FLAT_RADIUS)


def terrain_digest(layer):
    fields = ['verticesHeight', 'verticesWater', 'edgesPath', 'objectsTreeType',
              'objectsTreeSize', 'cellsTileSet', 'cellsMaterialSet', 'gridnavFlags']
    return hashlib.sha256(json.dumps({k: list(layer[k]) for k in fields},
                                     separators=(',', ':')).encode()).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    mode=ap.add_mutually_exclusive_group(required=True)
    mode.add_argument('--template', type=Path)
    mode.add_argument('--revise-current', action='store_true', help='Apply flat ground / sanctuary anchors to the current map')
    mode.add_argument('--stamp-overview', action='store_true',
                      help='Record geometry digest after exporting/copying a native minimap')
    args = ap.parse_args()
    if args.revise_current:
        path=ROOT/'content/maps/rift_arena.vmap'
        model=dm.load(str(path))
        layout=json.loads((ROOT/'content/maps/rift_arena.layout.json').read_text(encoding='utf-8'))
        revise_arena(model,layout)
        path.write_bytes(model.echo('binary',9))
        (ROOT/'content/maps/rift_arena.layout.json').write_text(json.dumps(layout,indent=2)+'\n',encoding='utf-8')
        return
    if args.stamp_overview:
        import struct
        header=(ROOT/'content/materials/overviews/rift_arena.tga').read_bytes()[:18]
        assert struct.unpack_from('<HH',header,12)==(512,512)
        p=ROOT/'content/maps/rift_arena.layout.json'
        layout=json.loads(p.read_text(encoding='utf-8'))
        layout['overview_map_sha256']=hashlib.sha256((ROOT/'content/maps/rift_arena.vmap').read_bytes()).hexdigest()
        p.write_text(json.dumps(layout,indent=2)+'\n',encoding='utf-8')
        print('Recorded overview geometry digest; this does not run or prove the native exporter')
        return
    model = dm.load(str(args.template))
    assert model.format_ver >= 40, 'Save a Forest Solo copy with the installed Hammer first (vmap 40+)'
    world = model.root['world']
    tile = next(e for e in model.elements if e.type == 'CMapDotaTileGrid')
    layer = tile['layerData'][0]
    assert layer['gridWidth'] == layer['gridHeight'] == 64
    assert sum(layer['edgesPath']) == 101, 'Unexpected base: use the installed Valve forest_solo'
    terrain_hash = terrain_digest(layer)
    discarded = []
    # Preserve art/terrain and common Dota shop/rune prefabs. All Overthrow
    # gameplay stays out of DUALITY, including nested entities inside groups.
    removed_classes = {'npc_dota_base', 'npc_dota_scripted_spawner', 'path_track',
                       'path_corner', 'ent_fow_revealer', 'npc_dota_tower',
                       'ent_dota_fountain', 'info_courier_spawn', 'info_player_start_dota',
                       'dota_custom_game_events', 'ent_dota_game_events', 'trigger_no_wards'}
    def keep(e):
        if e.type == 'CMapPrefab':
            p = e.get('targetMapPath', '')
            if p not in {'maps/prefabs/shop_sithil.vmap', 'maps/prefabs/rune_base.vmap'}:
                discarded.append(p)
                return False
        if e.type == 'CMapEntity':
            props = e['entity_properties']
            cl = props.get('classname', '')
            if cl in removed_classes or cl == 'info_particle_system' or (
                    cl == 'prop_static' and 'banner_' in props.get('model', '')):
                discarded.append(cl)
                return False
        if 'children' in e:
            e['children'] = dm.make_array([c for c in e['children'] if keep(c)], dm.Element)
        return True
    world['children'] = dm.make_array([e for e in world['children'] if keep(e)], dm.Element)
    node = max(e.get('nodeID', 0) for e in model.elements) + 100
    def entity(classname, name, x, y, z=160, extra=None):
        nonlocal node
        node += 1
        uid = uuid.uuid5(uuid.NAMESPACE_URL, 'duality/forest-reach/' + name)
        e = model.add_element(name, 'CMapEntity', id=uid)
        e['origin'], e['angles'], e['scales'] = dm.Vector3([x,y,z]), dm.Angle([0,0,0]), dm.Vector3([1,1,1])
        e['nodeID'], e['referenceID'] = node, dm.UInt64(0)
        e['children'] = dm.make_array([], dm.Element)
        e['editorOnly'], e['force_hidden'], e['isProceduralEntity'] = False, False, False
        e['variableTargetKeys'], e['variableNames'] = dm.make_array([], str), dm.make_array([], str)
        e['hitNormal'] = dm.Vector3([0,0,1])
        p = model.add_element(name+'_properties', 'EditGameClassProps',
                              id=uuid.uuid5(uid, 'properties'))
        p['classname'], p['targetname'] = classname, name
        for k,v in (extra or {}).items(): p[k] = str(v)
        e['entity_properties'] = p
        world['children'].append(e)
    layout = {'name':'The Verdant Reach', 'base':'Valve Overthrow forest_solo',
              'source_sha256':hashlib.sha256(args.template.read_bytes()).hexdigest(),
              'terrain_sha256':terrain_hash, 'bounds':[-5632,-5632,5632,5632],
              'spawns':[], 'relics':[], 'starts':[], 'bases':[], 'shops':[]}
    # One proven original native start from each of ten 36-degree pockets.
    # Two inner flank positions offer alternatives when outer pockets are camped.
    for i in range(12):
        if i < 10:
            a=math.radians(-36*i)
            x=round(1543.7163*math.cos(a)-4395.7759*math.sin(a))
            y=round(1543.7163*math.sin(a)+4395.7759*math.cos(a))
        else: x,y=0,(2200 if i==10 else -2200)
        p={'name':f'rift_spawn_{i+1:02}', 'x':x,'y':y,'z':160}
        layout['spawns'].append(p)
        entity('info_target',p['name'],x,y)
    # Both unused lobby pockets remain neutral terrain/shops. Actual first and
    # later spawns use the existing safety selection across all twelve points.
    for team,index in zip(TEAMS,[0,1,2,4,5,6,7,9]):
        p=layout['spawns'][index]
        layout['starts'].append({'team':team,'x':p['x'],'y':p['y']})
        layout['bases'].append({'x':p['x'],'y':p['y'],'z':160})
        entity('info_player_start_dota',f'rift_team_start_{team}',p['x'],p['y'],160,
               {'teamnumber':team,'Disabled':0})
    for i,(x,y) in enumerate([(0,700),(700,0),(0,-700),(-700,0)]):
        p={'name':f'rift_relic_{i+1:02}','x':x,'y':y,'z':288}
        layout['relics'].append(p)
        entity('info_target',p['name'],x,y,288)
    entity('ent_dota_game_events','rift_game_events',0,0)
    entity('info_target','rift_center',0,0,288)
    entity('info_target','rift_bounds_min',-5632,-5632)
    entity('info_target','rift_bounds_max',5632,5632)
    for e in model.elements:
        if e.type=='CMapPrefab' and e.get('targetMapPath')=='maps/prefabs/shop_sithil.vmap':
            x,y,z=e['origin'];layout['shops'].append({'x':x,'y':y,'z':z})
    assert len(layout['shops'])==10
    assert terrain_digest(layer)==terrain_hash, 'Terrain/navigation changed during gameplay stripping'
    layout['source_terrain_sha256']=terrain_hash
    revise_arena(model,layout)
    # Native source includes an embedded preview of the original Overthrow.
    model.prefix_attributes.clear()
    out=ROOT/'content/maps/rift_arena.vmap'
    out.write_bytes(model.echo('binary',9))
    (ROOT/'content/maps/rift_arena.layout.json').write_text(json.dumps(layout,indent=2)+'\n',encoding='utf-8')
    print(f'Wrote {out}: {out.stat().st_size} bytes; terrain preserved; removed {len(discarded)} old objects')

if __name__=='__main__': main()
