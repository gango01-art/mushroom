package.path="game/scripts/vscripts/?.lua;"..package.path
local B=require("rift.core.config").roshan
local check=arg[1]=="--check"
local function save(p,s)
 local f=io.open(p,"rb");local old=f and f:read("*a")or"";if f then f:close()end
 if old:gsub("\r\n","\n")==s:gsub("\r\n","\n")then return end
 assert(not check,"roshan generated data out of sync: "..p);f=assert(io.open(p,"wb"));f:write(s);f:close()
end
local values={BaseClass="npc_dota_creature",Model=B.model,SoundSet="Roshan",ModelScale=1,Level=30,IsAncient=1,IsNeutralUnitType=1,
 AttackCapabilities="DOTA_UNIT_CAP_MELEE_ATTACK",AttackDamageMin=B.damage,AttackDamageMax=B.damage,AttackRate=B.attack_rate,
 AttackAnimationPoint=.6,AttackRange=150,AttackAcquisitionRange=B.aggro,MovementCapabilities="DOTA_UNIT_CAP_MOVE_GROUND",MovementSpeed=B.move_speed,
 StatusHealth=B.health,StatusHealthRegen=B.regen,StatusMana=0,ArmorPhysical=B.armor,MagicalResistance=B.magic_resistance,
 VisionDaytimeRange=B.aggro,VisionNighttimeRange=B.aggro,BoundsHullName="DOTA_HULL_SIZE_HERO",HealthBarOffset=350,
 BountyGoldMin=0,BountyGoldMax=0,BountyXP=0}
for i,name in ipairs(B.abilities)do values["Ability"..i]=name end
local keys={};for k in pairs(values)do keys[#keys+1]=k end;table.sort(keys)
local out={'// Generated by tools/sync_roshan.lua.','"DOTAUnits"','{',' "'..B.unit..'"',' {'}
for _,k in ipairs(keys)do out[#out+1]='  "'..k..'" "'..values[k]..'"'end;out[#out+1]=' }\n}\n'
save("game/scripts/npc/npc_roshan_unit.txt",table.concat(out,"\n"))
local p="game/scripts/npc/npc_units_custom.txt";local f=assert(io.open(p,"rb"));local txt=f:read("*a");f:close()
if not txt:find('#base "npc_roshan_unit.txt"',1,true)then txt='#base "npc_roshan_unit.txt"\n'..txt end;save(p,txt)
for _,lang in ipairs({"russian","english"})do
 local p="game/resource/addon_"..lang..".txt";local f=assert(io.open(p,"rb"));local s=f:read("*a");f:close()
 local ru=lang=="russian"
 local tokens={[B.unit]=ru and"Рошан"or"Roshan",rift_roshan_name=ru and"Рошан"or"Roshan",
 rift_roshan_pocket_1=ru and"северо-запад"or"northwest",rift_roshan_pocket_2=ru and"юго-восток"or"southeast",
 rift_roshan_move=ru and"переход"or"moves in",rift_roshan_respawn=ru and"возрождение"or"respawns in",rift_roshan_travelling=ru and"идёт к"or"walking to"}
 for k,v in pairs(tokens)do local line='"'..k..'" "'..v..'"';local pat='"'..k..'"%s*"[^"\n]*"'
  if s:find(pat)then s=s:gsub(pat,function()return line end)else s=s:gsub('%s*}%s*}%s*$',function()return '\n\t\t'..line..'\n\t}\n}\n'end)end
 end
 save(p,s)
end
print("Roshan unit / localization synchronized")
