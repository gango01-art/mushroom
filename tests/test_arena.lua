local A = require("rift.core.arena")
local Stub = require("engine_stub")
T.case("arena guard returns escaping heroes to a safe inside point", function()
  local S=Stub.install()
  local h=S.hero("hero",0,2,Vector(5000,6000,128),{})
  local gm={map={bounds_min={x=-3584,y=-3584},bounds_max={x=3584,y=3584}},players={[0]={}}}
  require("rift.engine.arena_service").tick(gm)
  T.eq(h.pos.x,3424);T.eq(h.pos.y,3424)
  T.ok(A.inside(h.pos,gm.map.bounds_min,gm.map.bounds_max,160))
end)
T.case("standard dev map is not constrained by arena guard", function()
  local S=Stub.install()
  local h=S.hero("hero",0,2,Vector(5000,6000,128),{})
  require("rift.engine.arena_service").tick({map={fallback=true},players={[0]={}}})
  T.eq(h.pos.x,5000)
end)
T.case("arena validates spawn/relic positions and rejects inverted bounds", function()
  local c={bounds_min={x=-3000,y=-3000},bounds_max={x=3000,y=3000},spawns={{name="bad",x=9000,y=0}},relics={}}
  T.eq(#A.validate(c),1)
  c.bounds_max.x=-4000;T.eq(#A.validate(c),1)
end)
T.case("partial map contract falls back as a whole instead of leaving zero relic sites", function()
  Stub.install()
  _G.Entities={FindByName=function(_,_,name)
    if name:find("rift_spawn_",1,true)==1 then return {GetAbsOrigin=function() return Vector(0,0,128) end} end
  end}
  local map=require("rift.engine.map_contract").load(true)
  T.ok(map.fallback);T.eq(#map.spawns,12);T.eq(#map.relics,4)
end)
