local MatchState = require("rift.core.match_state")

T.case("forward transitions only, idempotent", function()
  local m = MatchState.new(T.config())
  local calls = 0
  m:on(function() calls = calls + 1 end)
  T.ok(m:advance("SETUP", 0))
  T.ok(not m:advance("SETUP", 1), "repeat ignored")
  T.ok(m:advance("HERO_SELECTION", 2))
  T.ok(not m:advance("SETUP", 3), "backwards ignored")
  T.ok(m:advance("ACTIVE", 10))
  T.eq(calls, 3)
  T.eq(m.active_start, 10)
end)

T.case("rewards only in ACTIVE/OVERTIME", function()
  local m = MatchState.new(T.config())
  m:advance("PREPARATION", 0)
  T.ok(not m:rewards_open())
  m:advance("ACTIVE", 1)
  T.ok(m:rewards_open())
  m:finish({ winner = 1 }, 2)
  T.ok(not m:rewards_open())
end)

T.case("finish exactly once, elapsed frozen", function()
  local m = MatchState.new(T.config())
  local fin = 0
  m:on(function(_, to) if to == "FINISHED" then fin = fin + 1 end end)
  m:advance("ACTIVE", 100)
  T.ok(m:finish({ winner = 1, reason = "score" }, 400))
  T.ok(not m:finish({ winner = 2, reason = "score" }, 401))
  T.eq(fin, 1)
  T.eq(m.result.winner, 1)
  T.eq(m:active_elapsed(9999), 300)
end)

T.case("remaining uses game time, not tick count", function()
  local cfg = T.config()
  local m = MatchState.new(cfg)
  m:advance("ACTIVE", 50)
  T.eq(m:active_remaining(50), cfg.match.active_seconds)
  T.eq(m:active_remaining(50 + 60), cfg.match.active_seconds - 60)
end)
