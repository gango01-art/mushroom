local B = require("rift.data.hero_balance")
local S = require("rift.core.heroes.sf_physical")
local R = require("rift.core.heroes.sf_magical")
local P, MG = B.sf.requiem_physical, B.sf.requiem_magical

T.case("spheres: start 4, one per attack, never more than 4", function()
  local s = S.start(P, 3, 0)
  T.eq(s.charges, 4)
  T.ok(s:consume(0.1, true)); T.eq(s.charges, 3)
  T.ok(not s:consume(0.1, false), "invalid target spends nothing"); T.eq(s.charges, 3)
  s:update(1.6); T.eq(s.charges, 4, "regen 1.5 at rank 3")
  s:update(10); T.eq(s.charges, 4, "no hidden bank above max")
end)

T.case("spheres: regen per stage from free slot, empty still allows attacks", function()
  local s = S.start(P, 1, 0)
  for _ = 1, 4 do T.ok(s:consume(0, true)) end
  T.ok(not s:consume(0, true), "no sphere: normal attack")
  s:update(1.8); T.eq(s.charges, 1)
  s:update(3.5); T.eq(s.charges, 1)
  s:update(3.6); T.eq(s.charges, 2)
end)

T.case("spheres: duration 15 s then nothing", function()
  local s = S.start(P, 2, 0)
  s:update(15); T.ok(not s.active); T.eq(s.charges, 0)
  T.ok(not s:consume(15.1, true))
  T.eq(s:claim_raze(15.1, 1, "v"), nil)
end)

T.case("sphere damage 60% of attack damage without crit", function()
  local s = S.start(P, 1, 0)
  T.ok(math.abs(s:sphere_damage(200) - 120) < 1e-9)
end)

T.case("shadowraze bonus once per cast and victim, 40/60/80%", function()
  local s = S.start(P, 2, 0)
  T.eq(s:claim_raze(1, 7, "v1"), 0.60)
  T.eq(s:claim_raze(1, 7, "v1"), nil)
  T.eq(s:claim_raze(1, 7, "v2"), 0.60)
  T.eq(s:claim_raze(2, 8, "v1"), 0.60, "new cast")
end)

T.case("rings: telegraph 0.4 s before, erupt at 0.6/1.2/1.8, fixed centre, 8 points", function()
  local r = R.start(MG, 1, 1, { x = 100, y = 0 }, 10)
  local ev = r:due(10.2)
  T.eq(#ev, 1); T.eq(ev[1].kind, "telegraph"); T.eq(ev[1].ring, 1)
  ev = r:due(10.6)
  T.eq(ev[1].kind, "erupt"); T.eq(ev[1].radius, 300); T.eq(#ev[1].points, 8)
  T.ok(math.abs(ev[1].points[1].x - 400) < 1e-9, "centre fixed at cast point")
  ev = r:due(12)
  local kinds = {}
  for _, e in ipairs(ev) do kinds[#kinds + 1] = e.kind .. e.ring end
  T.eq(table.concat(kinds, ","), "telegraph2,erupt2,telegraph3,erupt3")
  T.ok(r:finished())
end)

T.case("rings: one packet per ring per victim; three rings can hit three times", function()
  local r = R.start(MG, 2, 1, { x = 0, y = 0 }, 0)
  T.eq(r:resolve_hit(1, "v:1", "normal").damage, 100)
  T.eq(r:resolve_hit(1, "v:1", "normal"), nil, "neighbouring eruption same ring")
  T.eq(r:resolve_hit(2, "v:1", "normal").damage, 100)
  T.eq(r:resolve_hit(3, "v:1", "normal").damage, 100)
  T.eq(r:resolve_hit(1, "v:2", "normal").damage, 100, "new life cycle is a new victim")
end)

T.case("rings: debuff immune -> zero damage, one short fear per cast; invulnerable -> nothing", function()
  local r = R.start(MG, 3, 1, { x = 0, y = 0 }, 0)
  local h = r:resolve_hit(1, "a", "debuff_immune")
  T.eq(h.damage, 0); T.eq(h.fear, 1.0)
  h = r:resolve_hit(2, "a", "debuff_immune")
  T.eq(h.damage, 0); T.eq(h.fear, 0, "fear once per cast")
  T.eq(r:resolve_hit(1, "b", "invulnerable"), nil)
  T.eq(r:resolve_hit(3, "a", "normal").fear, 0, "immunity gone between rings: normal damage, no fear")
end)

T.case("rings: cancel at match end stops further events", function()
  local r = R.start(MG, 1, 1, { x = 0, y = 0 }, 0)
  r:due(0.7); r:cancel()
  T.eq(#r:due(5), 0); T.ok(r:finished())
end)
