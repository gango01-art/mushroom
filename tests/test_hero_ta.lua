local B = require("rift.data.hero_balance")
local C = require("rift.core.heroes.ta_physical")
local W = require("rift.core.heroes.ta_magical")
local CC, WC = B.ta.crystal_physical, B.ta.waves_magical

T.case("crystal: radius/cooldown by ultimate rank, no own damage coefficient", function()
  T.eq(C.new(CC, 1, 0):radius(), 320); T.eq(C.new(CC, 3, 0):radius(), 460)
  T.eq(CC.cooldown[2], 9)
  T.eq(CC.damage_coefficient, nil); T.eq(CC.coefficient, nil)
end)

T.case("crystal: 3 durability; TA third hit pulses then breaks; enemy hits never pulse", function()
  local c = C.new(CC, 1, 0)
  local a = c:on_attacked("owner"); T.ok(a.pulse_id); T.ok(not a.destroyed)
  local e = c:on_attacked("enemy"); T.eq(e.pulse_id, nil)
  local t = c:on_attacked("owner"); T.ok(t.pulse_id); T.ok(t.destroyed)
  T.ok(a.pulse_id ~= t.pulse_id)
  local c2 = C.new(CC, 1, 0)
  c2:on_attacked("owner"); c2:on_attacked("owner")
  local last = c2:on_attacked("enemy"); T.eq(last.pulse_id, nil); T.ok(last.destroyed)
end)

T.case("crystal: illusions/summons ignored; expiry gives no pulse", function()
  local c = C.new(CC, 1, 0)
  T.eq(c:on_attacked("other").pulse_id, nil); T.eq(c.durability, 3)
  T.ok(c:expired(6)); c:remove(); T.ok(not c.alive)
end)

T.case("crystal: one hit per hero per pulse", function()
  local c = C.new(CC, 1, 0)
  local p = c:on_attacked("owner").pulse_id
  T.ok(c:claim(p, "h:1")); T.ok(not c:claim(p, "h:1")); T.ok(c:claim(p, "h2:1"))
end)

T.case("pulse damage = full source hit x Psi Blades coefficient (fixture 0.8)", function()
  T.eq(C.pulse_damage(250 + 280, 0.8), 424)
  T.eq(C.pulse_damage(250, 0.8), 200)
end)

T.case("waves: base + 60% intellect snapshot, one hit per wave per victim", function()
  local w = W.new()
  local id, dmg = w:release(0, WC.q_base, 30, WC.intellect_scaling, 0, 2)
  T.eq(dmg, 138)
  T.eq(w:claim(id, "a:1", 0.1), 138); T.eq(w:claim(id, "a:1", 0.2), nil); T.eq(w:claim(id, "b:1", 0.2), 138)
  local id2 = w:release(0, WC.e_base[4], 0, WC.intellect_scaling, 0, 2)
  T.eq(w:claim(id2, "a:1", 0.3), 180, "different wave hits again")
  T.eq(w:claim(id, "c:1", 3), nil, "expired")
  w:cleanup(5); T.eq(w:count(), 0)
  T.eq(W.half_width(WC.width), 90)
end)
